export function taskPrompt(plan: Plan, task: TaskSpec, doneTasks: { id: string; title: string; summary?: string }[], retryReason?: string): string {
  const deps = doneTasks.length
    ? `\nУже сделано другими агентами:\n${doneTasks.map((t) => `- ${t.title}${t.summary ? `: ${oneLine(t.summary)}` : ''}`).join('\n')}\n`
    : '';
  const acceptance = task.acceptance.length ? `\nКритерии готовности:\n${task.acceptance.map((a) => `- ${a}`).join('\n')}\n` : '';
  const retry = retryReason ? `\nПредыдущая попытка не прошла проверку. Исправь проблему:\n${retryReason}\n` : '';
  return `Задача «${task.title}» (id: ${task.id}).

${task.description}
${acceptance}${deps}${retry}
Когда закончишь, кратко (3–6 строк) опиши, что сделано и как это проверить.`;
}

export function conflictPrompt(files: string[]): string {
  return `При слиянии твоей ветки со свежей версией main возникли конфликты в файлах:
${files.map((f) => `- ${f}`).join('\n')}

Открой эти файлы, разреши конфликты (маркеры <<<<<<< ======= >>>>>>>), сохранив изменения обеих сторон по смыслу.
Удали все маркеры конфликта. Коммит не делай — студия сделает его сама.`;
}

function oneLine(s: string): string {
  const t = s.replace(/\s+/g, ' ').trim();
  return t.length > 200 ? `${t.slice(0, 199)}…` : t;
}
