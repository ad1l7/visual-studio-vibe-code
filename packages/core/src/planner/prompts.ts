export function buildFullSpec(spec: string, questions: { id: string; question: string }[] = [], answers: Record<string, string> = {}): string {
  const qa = questions
    .filter((q) => answers[q.id]?.trim())
    .map((q) => `- ${q.question}\n  Ответ: ${answers[q.id]!.trim()}`)
    .join('\n');
  return `ТЗ:\n${spec.trim()}${qa ? `\n\nУточнения заказчика:\n${qa}` : ''}`;
}

