export interface SpecCheck {
  id: string;
  label: string;
  /** Что дописать по кнопке «+». */
  append: string;
  test: (s: string) => boolean;
}

export const SPEC_CHECKS: SpecCheck[] = [
  { id: 'who', label: 'Для кого', append: '\nДля кого: ', test: (s) => /(для |клиент|покупател|пользовател|ученик|студент|сотрудник|посетител|гост|аудитор|команд)/.test(s) },
  { id: 'what', label: 'Что можно делать', append: '\nЧто можно делать: ', test: (s) => (s.match(/[,;\n]/g)?.length ?? 0) >= 2 || s.length >= 160 },
  { id: 'auth', label: 'Вход и личный кабинет', append: '\nВход: ', test: (s) => /(вход|регистрац|логин|личн\S* кабинет|аккаунт|роль|без входа)/.test(s) },
  { id: 'where', label: 'Где работает', append: '\nГде пользоваться: сайт / телефон / Telegram', test: (s) => /(сайт|телефон|мобильн|приложени|telegram|телеграм|бот|компьютер|планшет)/.test(s) },
  { id: 'pay', label: 'Оплата', append: '\nОплата: ', test: (s) => /(оплат|платеж|карт(ой|а|у)|подписк|абонемент|бесплатн|без оплаты)/.test(s) },
  { id: 'look', label: 'Внешний вид', append: '\nВнешний вид: ', test: (s) => /(дизайн|стиль|цвет|как у |минималист|светл|темн|логотип|бренд)/.test(s) },
];

export function specCompleteness(spec: string): { passed: Set<string>; score: number; label: string } {
  const s = spec.toLowerCase().replace(/ё/g, 'е');
  const passed = new Set(spec.trim() ? SPEC_CHECKS.filter((c) => c.test(s)).map((c) => c.id) : []);
  const score = passed.size;
  return { passed, score, label: score <= 2 ? 'Коротко' : score <= 4 ? 'Неплохо' : 'Подробно' };
}
